"""Generate the 12 x 12 CJK bitmap font of the RLCD 4.2 music page.

The glyphs come from the Fusion Pixel 12px font (SIL Open Font License 1.1),
rasterised on the twelve pixel grid the font was drawn for. The panel's own
5 x 7 font only covers ASCII, so Chinese song titles and lyrics need a font of
their own; this script turns the font into the two tables the firmware looks up:

- ``kCjkCodepoints`` holds the covered code points in ascending order.
- ``kCjkGlyphData`` holds one glyph per code point: twelve rows of twelve
  pixels, two bytes per row, most significant bit leftmost.

Usage:

    python3 tools/rlcd42/gen_cjk_font.py --font fusion-pixel-12px-monospaced-zh_hans.ttf \
        --output firmware/targets/waveshare_rlcd_42/main/cjk_font_data.cpp

Pillow rasterises the font; it is a generator dependency and is not needed to
build the firmware.
"""

from __future__ import annotations

import argparse
from pathlib import Path

GLYPH_SIZE = 12
BYTES_PER_GLYPH = 2 * GLYPH_SIZE
# GB2312 rows that hold the hanzi of level 1 and level 2.
_HANZI_ROWS = range(0xB0, 0xF8)
# GB2312 rows that hold the full-width punctuation the lyrics use.
_PUNCTUATION_ROWS = (0xA1, 0xA2)


def charset() -> list[int]:
    """Code points the font has to cover, in ascending order."""

    points: set[int] = set()
    for first in list(_HANZI_ROWS) + list(_PUNCTUATION_ROWS):
        for second in range(0xA1, 0xFF):
            try:
                points.add(ord(bytes((first, second)).decode("gb2312")))
            except UnicodeDecodeError:
                continue
    return sorted(points)


def rasterise(font, points: list[int]) -> tuple[bytes, int]:
    """Render every code point and pack the pixels; returns the data and the widest glyph."""

    from PIL import Image, ImageDraw

    image = Image.new("L", (GLYPH_SIZE, GLYPH_SIZE), 0)
    draw = ImageDraw.Draw(image)
    packed = bytearray()
    widest = 0
    for point in points:
        image.paste(0, (0, 0, GLYPH_SIZE, GLYPH_SIZE))
        draw.text((0, 0), chr(point), font=font, fill=255)
        pixels = image.load()
        for row in range(GLYPH_SIZE):
            bits = 0
            for column in range(GLYPH_SIZE):
                if pixels[column, row] > 127:
                    bits |= 1 << (GLYPH_SIZE - 1 - column)
            packed.append(bits >> 8)
            packed.append(bits & 0xFF)
        box = image.getbbox()
        if box:
            widest = max(widest, box[2] - box[0])
    return bytes(packed), widest


def emit(output: Path, points: list[int], data: bytes) -> None:
    """Write the generated tables as a C++ source file."""

    lines = [
        "// Generated by tools/rlcd42/gen_cjk_font.py; do not edit by hand.",
        "//",
        "// Glyphs of the Fusion Pixel 12px font (OFL-1.1), rasterised on a 12 x 12 grid.",
        "#include \"cjk_font_data.hpp\"",
        "",
        "namespace usage_panel::rlcd::cjk_data {",
        "",
        "extern const uint16_t kCjkCodepoints[] = {",
    ]
    for start in range(0, len(points), 12):
        chunk = points[start:start + 12]
        lines.append("    " + " ".join(f"0x{point:04X}," for point in chunk))
    lines += [
        "};",
        "",
        "extern const uint8_t kCjkGlyphData[] = {",
    ]
    for start in range(0, len(data), 18):
        chunk = data[start:start + 18]
        lines.append("    " + " ".join(f"0x{byte:02X}," for byte in chunk))
    lines += [
        "};",
        "",
        f"extern const int kCjkGlyphCount = {len(points)};",
        "",
        "}  // namespace usage_panel::rlcd::cjk_data",
        "",
    ]
    output.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", type=Path, required=True, help="path of the Fusion Pixel TTF")
    parser.add_argument("--output", type=Path, required=True, help="generated C++ file")
    arguments = parser.parse_args()

    from PIL import ImageFont

    font = ImageFont.truetype(str(arguments.font), GLYPH_SIZE)
    points = charset()
    data, widest = rasterise(font, points)
    emit(arguments.output, points, data)
    print(
        f"{len(points)} glyphs, {len(data)} bytes of glyph data, "
        f"widest glyph {widest} px"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
